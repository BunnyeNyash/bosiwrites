$(document).ready(function () {
  // --- Hamburger menu ---
  $('#hamburger').click(function () {
    $('#main-menu').toggleClass('open');
  });

  // --- Search toggle ---
  $('#search-toggle').click(function () {
    $('#nav-search').slideToggle(300);
    $(this).find('i').toggleClass('fa-search fa-times');
  });

  // --- Dark mode (persisted across visits) ---
  function applyTheme(isDark) {
    $('body').toggleClass('dark-mode', isDark);
    $('#theme-toggle').html(isDark ? '<i class="fas fa-sun"></i>' : '<i class="fas fa-moon"></i>');
  }
  var savedTheme = localStorage.getItem('bosiwrites-theme');
  applyTheme(savedTheme === 'dark');
  $('#theme-toggle').click(function () {
    var isDark = !$('body').hasClass('dark-mode');
    applyTheme(isDark);
    localStorage.setItem('bosiwrites-theme', isDark ? 'dark' : 'light');
  });

  // --- Hero slider ---
  var currentSlide = 0;
  var slideCount = $('.slide-item').length;
  function goToSlide(idx) {
    currentSlide = (idx + slideCount) % slideCount;
    $('.slider-track').css('transform', 'translateX(-' + (currentSlide * 100) + '%)');
    $('.slide-dots .dot').removeClass('active').eq(currentSlide).addClass('active');
  }
  if (slideCount > 1) {
    $('.slide-dots .dot').click(function () { goToSlide($(this).index()); });
    $('#slide-next').click(function () { goToSlide(currentSlide + 1); });
    $('#slide-prev').click(function () { goToSlide(currentSlide - 1); });
    setInterval(function () { goToSlide(currentSlide + 1); }, 6000);
  } else {
    $('.slide-arrows, .slide-dots').hide();
  }

  // --- Client-side search (reads /search-index.json, generated by Hugo at build time) ---
  var searchIndex = null;
  function loadIndex(callback) {
    if (searchIndex) { callback(); return; }
    $.getJSON('/search-index.json', function (data) {
      searchIndex = data;
      callback();
    });
  }
  var $input = $('.search-input');
  var $results = $('#search-results');
  $input.on('input', function () {
    var q = $(this).val().trim().toLowerCase();
    if (q.length < 2) { $results.hide().empty(); return; }
    loadIndex(function () {
      var matches = searchIndex.filter(function (post) {
        return post.title.toLowerCase().indexOf(q) !== -1;
      }).slice(0, 8);
      $results.empty();
      if (matches.length === 0) {
        $results.append('<a href="#">No results found</a>');
      } else {
        matches.forEach(function (post) {
          $results.append('<a href="' + post.url + '">' + post.title + '</a>');
        });
      }
      $results.show();
    });
  });
  $(document).on('click', function (e) {
    if (!$(e.target).closest('#nav-search').length) { $results.hide(); }
  });

  // --- Newsletter form (inline AJAX submit, no page navigation) ---
  var $newsletterForm = $('#newsletter-form');
  var $newsletterMsg = $('#newsletter-message');
  if ($newsletterForm.length) {
    $newsletterForm.on('submit', function (e) {
      e.preventDefault();
      var form = this;
      var $form = $(form);
      var actionUrl = $form.attr('action');
      if (!actionUrl) return;
      var $button = $form.find('button[type="submit"]');
      $button.prop('disabled', true).text('Subscribing...');
      $newsletterMsg.removeClass('success error').hide();

      fetch(actionUrl, {
        method: 'POST',
        body: new FormData(form),
        headers: { 'Accept': 'application/json' }
      }).then(function (response) {
        if (response.ok) {
          $form.hide();
          $newsletterMsg.text('Thanks for subscribing! 🎉').addClass('success').show();
        } else {
          response.json().then(function (data) {
            var errorMsg = (data && data.errors && data.errors.length)
              ? data.errors.map(function (err) { return err.message; }).join(', ')
              : 'Something went wrong. Please try again.';
            $newsletterMsg.text(errorMsg).addClass('error').show();
            $button.prop('disabled', false).text('Subscribe');
          });
        }
      }).catch(function () {
        $newsletterMsg.text('Something went wrong. Please try again.').addClass('error').show();
        $button.prop('disabled', false).text('Subscribe');
      });
    });
  }
});
